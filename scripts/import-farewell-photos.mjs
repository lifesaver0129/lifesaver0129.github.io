import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, stat, unlink, writeFile } from 'node:fs/promises';
import { basename, dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);
const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const sourceRoot = process.argv[2] ?? '/Users/yuxihu/Downloads/photos';
const outputRoot = join(projectRoot, 'public', 'farewell', 'photos');
const manifestPath = join(projectRoot, 'src', 'farewellPhotos.ts');
const supportedExtensions = new Set(['.heic', '.jpeg', '.jpg', '.png', '.webp']);
const rotationByFilename = new Map([
  ['20260103_113847.JPG', 90],
]);
const createdDateOverrideByFilename = new Map([
  ['8DEAF8B4-06AD-4CAE-AE4C-7F63214E3DD9.JPG', '2025-07-03T22:06:06+08:00'],
  ['1148.JPG', '2024-03-06T22:20:33+08:00'],
  ['IMG_8087.JPG', '2023-11-03T23:32:17+08:00'],
  ['4393.JPG', '2025-12-06T23:50:46+08:00'],
]);
const displayDateFormatter = new Intl.DateTimeFormat('en-US', {
  day: 'numeric',
  month: 'long',
  timeZone: 'Asia/Shanghai',
  year: 'numeric',
});
const localDatePartsFormatter = new Intl.DateTimeFormat('en-CA', {
  day: '2-digit',
  hour: '2-digit',
  hourCycle: 'h23',
  minute: '2-digit',
  month: '2-digit',
  second: '2-digit',
  timeZone: 'Asia/Shanghai',
  year: 'numeric',
});

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  }));

  return paths.flat();
}

function parseSpotlightDate(value) {
  const match = value.trim().match(
    /^(\d{4}-\d{2}-\d{2}) (\d{2}:\d{2}:\d{2}) ([+-]\d{4})$/,
  );

  if (!match) return null;

  const offset = `${match[3].slice(0, 3)}:${match[3].slice(3)}`;
  const date = new Date(`${match[1]}T${match[2]}${offset}`);
  return Number.isNaN(date.valueOf()) ? null : date;
}

async function getCreatedDate(path) {
  const createdDateOverride = createdDateOverrideByFilename.get(basename(path));

  if (createdDateOverride) {
    return new Date(createdDateOverride);
  }

  try {
    const { stdout } = await run('mdls', ['-raw', '-name', 'kMDItemContentCreationDate', path]);
    const spotlightDate = parseSpotlightDate(stdout);
    if (spotlightDate) return spotlightDate;
  } catch {
    // Fall through to the filesystem date when Spotlight metadata is unavailable.
  }

  return (await stat(path)).birthtime;
}

async function getImageDimensions(path) {
  const { stdout } = await run('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', path]);
  const width = Number(stdout.match(/pixelWidth:\s*(\d+)/)?.[1]);
  const height = Number(stdout.match(/pixelHeight:\s*(\d+)/)?.[1]);

  if (!width || !height) {
    throw new Error(`Could not read image dimensions for ${path}`);
  }

  return { height, width };
}

function getLocalParts(date) {
  return Object.fromEntries(
    localDatePartsFormatter.formatToParts(date)
      .filter((part) => part.type !== 'literal')
      .map((part) => [part.type, part.value]),
  );
}

function createManifest(photoRecords) {
  const photosByYear = new Map();
  for (const photo of photoRecords) {
    const yearPhotos = photosByYear.get(photo.year) ?? [];
    yearPhotos.push(photo);
    photosByYear.set(photo.year, yearPhotos);
  }
  const lines = [
    '// Generated by scripts/import-farewell-photos.mjs. Do not edit by hand.',
    '',
    'export type FarewellPhoto = {',
    '  src: string;',
    '  date: string;',
    '  alt: string;',
    '  width: number;',
    '  height: number;',
    "  orientation: 'landscape' | 'portrait' | 'square';",
    '};',
    '',
    'export const farewellPhotosByYear: Record<number, FarewellPhoto[]> = {',
  ];

  for (const [year, photos] of [...photosByYear.entries()].sort(([a], [b]) => a - b)) {
    lines.push(`  ${year}: [`);
    for (const photo of photos) {
      lines.push('    {');
      lines.push(`      src: ${JSON.stringify(photo.src)},`);
      lines.push(`      date: ${JSON.stringify(photo.dateLabel)},`);
      lines.push(`      alt: ${JSON.stringify(`Farewell memory from ${photo.dateLabel}`)},`);
      lines.push(`      width: ${photo.width},`);
      lines.push(`      height: ${photo.height},`);
      lines.push(`      orientation: ${JSON.stringify(photo.orientation)},`);
      lines.push('    },');
    }
    lines.push('  ],');
  }

  lines.push('};', '');
  return lines.join('\n');
}

const sourceFiles = (await walk(sourceRoot))
  .filter((path) => supportedExtensions.has(extname(path).toLowerCase()))
  .sort((a, b) => a.localeCompare(b));

if (sourceFiles.length === 0) {
  throw new Error(`No supported photos found in ${sourceRoot}`);
}

await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });

const datedPhotos = await Promise.all(sourceFiles.map(async (path) => ({
  createdAt: await getCreatedDate(path),
  path,
})));

datedPhotos.sort((a, b) => (
  a.createdAt.valueOf() - b.createdAt.valueOf()
  || a.path.localeCompare(b.path)
));

const usedNames = new Map();
const importedImageHashes = new Set();
const photoRecords = [];

for (const [index, photo] of datedPhotos.entries()) {
  const parts = getLocalParts(photo.createdAt);
  const timestamp = `${parts.year}-${parts.month}-${parts.day}_${parts.hour}-${parts.minute}-${parts.second}`;
  const duplicateNumber = (usedNames.get(timestamp) ?? 0) + 1;
  usedNames.set(timestamp, duplicateNumber);

  const filename = `${timestamp}${duplicateNumber > 1 ? `-${String(duplicateNumber).padStart(2, '0')}` : ''}.jpg`;
  const year = Number(parts.year);
  const yearOutputRoot = join(outputRoot, parts.year);
  const outputPath = join(yearOutputRoot, filename);
  await mkdir(yearOutputRoot, { recursive: true });
  await run('sips', [
    '-s', 'format', 'jpeg',
    '-s', 'formatOptions', '72',
    '-Z', '1400',
    photo.path,
    '--out', outputPath,
  ]);

  const rotation = rotationByFilename.get(basename(photo.path));
  if (rotation) {
    await run('sips', ['-r', String(rotation), outputPath]);
  }

  const imageHash = createHash('sha256').update(await readFile(outputPath)).digest('hex');
  if (importedImageHashes.has(imageHash)) {
    await unlink(outputPath);
    console.log(`Skipped exact duplicate: ${basename(photo.path)}`);

    if ((index + 1) % 10 === 0 || index + 1 === datedPhotos.length) {
      console.log(`Processed ${index + 1}/${datedPhotos.length}`);
    }
    continue;
  }
  importedImageHashes.add(imageHash);

  const { height, width } = await getImageDimensions(outputPath);
  const orientation = width === height ? 'square' : width > height ? 'landscape' : 'portrait';

  photoRecords.push({
    dateLabel: displayDateFormatter.format(photo.createdAt),
    height,
    orientation,
    src: `/farewell/photos/${parts.year}/${filename}`,
    width,
    year,
  });

  if ((index + 1) % 10 === 0 || index + 1 === datedPhotos.length) {
    console.log(`Processed ${index + 1}/${datedPhotos.length}`);
  }
}

await writeFile(manifestPath, createManifest(photoRecords), 'utf8');

console.log(`Photos: ${relative(projectRoot, outputRoot)}`);
console.log(`Manifest: ${relative(projectRoot, manifestPath)}`);
